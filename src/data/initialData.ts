// Helper to get formatted date string for realistic mock records
function getDemoTimestamp(hoursAgo: number, minsAgo: number = 0): { full: string; dateOnly: string } {
  const d = new Date(Date.now() - (hoursAgo * 3600 * 1000 + minsAgo * 60 * 1000));
  const day = String(d.getDate()).padStart(2, '0');
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const year = d.getFullYear();
  const time = d.toLocaleTimeString('id-ID', { hour: '2-digit', minute: '2-digit' });
  return {
    full: `${day}/${month}/${year} ${time}`,
    dateOnly: `${day}/${month}/${year}`,
  };
}

